<?php

/* Compound Assignment -> Start with $x = 10. Use compound assignment operators (+=, -
=, *=, /=, %=) to modify and display x after each operation.*/

$x = 10;

echo "Initial value: $x <br>";

$x += 5;
echo "After += 5: $x <br>";

$x -= 3;
echo "After -= 3: $x <br>";

$x *= 2;
echo "After *= 2: $x <br>";

$x /= 4;
echo "After /= 4: $x <br>";

$x %= 3;
echo "After %= 3: $x <br>";

?>