<?php

 /*Increment/Decrement -> Demonstrate pre-increment and post-increment operators.Show how a++ and ++a differ */


 #post-increment operators
 $num = 10;
 echo'Before $num++: ' . $num . '<br>';
 $num++;
 echo'After $num++: ' . $num . '<br>';

 #pre-increment operators
 echo'Before ++$num: ' . $num . '<br>';
 ++$num;
 echo'After ++$num: ' . $num . '<br>';


